#!/usr/bin/env python3
"""Generate the resampler table the DSP needs (pure Python, no numpy).

Braids runs at its native 96 kHz. Move runs at 44.1 kHz. The ratio is exactly
147/320, so the 96k -> 44.1k resampler is a polyphase FIR with 147 phases:
every output sample sits at input time n * 320/147, whose fractional part is
always one of r/147, r = 0..146.

The kernel is a Kaiser-windowed sinc. Each phase is normalised to unity DC
gain so a DC input never becomes a 147-periodic ripple.
"""
import math
import pathlib
import sys


def i0(x):
    """Modified Bessel function of the first kind, order 0 (series)."""
    s, term, k = 1.0, 1.0, 1
    while term > 1e-12 * s:
        term *= (x / (2.0 * k)) ** 2
        s += term
        k += 1
    return s


def kaiser(t, half, beta):
    """Kaiser window at offset t from the centre, support |t| <= half."""
    r = t / half
    if abs(r) > 1.0:
        return 0.0
    return i0(beta * math.sqrt(1.0 - r * r)) / i0(beta)


def sinc(x):
    return 1.0 if x == 0 else math.sin(math.pi * x) / (math.pi * x)


RS_UP, RS_DOWN = 147, 320          # 44100/96000 = 147/320
RS_TAPS = 64                       # input samples per output sample
RS_HALF = RS_TAPS // 2             # taps k = -31..32 around the output time
RS_CUTOFF_HZ = 22050.0             # -6 dB point; passband ~19k, stop ~25.5k
RS_BETA = 6.8                      # ~70 dB stopband
fc = RS_CUTOFF_HZ / 96000.0        # cycles per input sample

rs_rows = []
for r in range(RS_UP):
    frac = r / RS_UP
    row = []
    for k in range(-RS_HALF + 1, RS_HALF + 1):
        t = frac - k               # distance from input sample q+k to output time q+frac
        row.append(2.0 * fc * sinc(2.0 * fc * t) * kaiser(t, RS_HALF + 0.5, RS_BETA))
    g = sum(row)
    rs_rows.append([v / g for v in row])

def fmt(values, per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append("  " + ", ".join("%.9ef" % v for v in values[i:i + per_line]) + ",")
    return "\n".join(lines)


out = ["/* Generated by scripts/gen_tables.py. Do not edit. */",
       "#pragma once",
       "",
       "#define OBRAIDS_RS_UP %d" % RS_UP,
       "#define OBRAIDS_RS_DOWN %d" % RS_DOWN,
       "#define OBRAIDS_RS_TAPS %d" % RS_TAPS,
       "#define OBRAIDS_RS_HALF %d" % RS_HALF,
       "",
       "/* obraids_rs_table[r][j]: weight of input sample q + (j - OBRAIDS_RS_HALF + 1)",
       " * for the output at input time q + r/OBRAIDS_RS_UP. */",
       "static const float obraids_rs_table[OBRAIDS_RS_UP][OBRAIDS_RS_TAPS] = {"]
for row in rs_rows:
    out.append(" {")
    out.append(fmt(row))
    out.append(" },")
out.append("};")
out.append("")

path = pathlib.Path(sys.argv[1])
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text("\n".join(out))
